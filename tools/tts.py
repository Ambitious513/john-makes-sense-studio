"""
TTS → narration audio + REAL word timings, in one command.

Companion to psychology-channel/src/engine/voice.tsx, which consumes the
`<out>.words.json` contract (word, f0, f1 at the project fps) to drive visemes
and caption timing. The audio is generated by edge-tts (free neural voices), so
the contract is provider-agnostic: swapping in ElevenLabs later only replaces
this script.

    python tools/tts.py "Your line here." --out psychology-channel/public/voice/pilot20-l1.mp3 \
        --voice en-US-AndrewNeural --rate=-2% --fps 30

Writes <out>.mp3 and <out>.words.json, then prints the measured duration and the
speech rate so timing decisions are made on numbers, not guesses.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import subprocess
import sys
from pathlib import Path

import edge_tts


def probe_duration(path: Path) -> float:
    out = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-show_entries",
            "format=duration",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.strip()
    return float(out)


def probe_rate(path: Path) -> tuple[int, int]:
    out = subprocess.run(
        [
            "ffprobe",
            "-v",
            "error",
            "-select_streams",
            "a:0",
            "-show_entries",
            "stream=sample_rate,channels",
            "-of",
            "default=noprint_wrappers=1:nokey=1",
            str(path),
        ],
        capture_output=True,
        text=True,
        check=True,
    ).stdout.split()
    return int(out[0]), int(out[1])


async def synth(text: str, voice: str, rate: str, volume: str, pitch: str, out: Path):
    communicate = edge_tts.Communicate(
        text, voice, rate=rate, volume=volume, pitch=pitch, boundary="WordBoundary"
    )
    words: list[dict] = []
    with out.open("wb") as fh:
        async for chunk in communicate.stream():
            if chunk["type"] == "audio":
                fh.write(chunk["data"])
            elif chunk["type"] == "WordBoundary":
                # offset/duration are in 100 ns ticks
                start = chunk["offset"] / 1e7
                dur = chunk["duration"] / 1e7
                words.append(
                    {
                        "word": chunk["text"],
                        "start": start,
                        "end": start + dur,
                    }
                )
    return words


def main() -> int:
    ap = argparse.ArgumentParser(description="edge-tts narration + word timings")
    ap.add_argument("text", help="line to speak")
    ap.add_argument("--out", required=True, help="output .mp3 path")
    ap.add_argument("--voice", default="en-US-AndrewNeural")
    ap.add_argument("--rate", default="+0%", help='e.g. "+0%%", "-4%%"')
    ap.add_argument("--volume", default="+0%")
    ap.add_argument("--pitch", default="+0Hz")
    ap.add_argument("--fps", type=int, default=30)
    ap.add_argument("--json", default=None, help="override words.json path")
    args = ap.parse_args()

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    words = asyncio.run(
        synth(args.text, args.voice, args.rate, args.volume, args.pitch, out)
    )
    seconds = probe_duration(out)
    sr, ch = probe_rate(out)

    fps = args.fps
    total_frames = round(seconds * fps)
    packed = [
        {
            "word": w["word"],
            "f0": round(w["start"] * fps),
            "f1": max(round(w["end"] * fps), round(w["start"] * fps) + 1),
        }
        for w in words
    ]
    doc = {
        "text": args.text,
        "voice": args.voice,
        "fps": fps,
        "seconds": round(seconds, 3),
        "totalFrames": total_frames,
        "words": packed,
    }
    json_path = Path(args.json) if args.json else out.with_suffix(".words.json")
    json_path.write_text(json.dumps(doc, indent=2), encoding="utf-8")

    n_words = len(args.text.split())
    print(f"audio     : {out}  ({out.stat().st_size} B, {sr} Hz, {ch} ch)")
    print(f"duration  : {seconds:.3f} s  -> {total_frames} frames @ {fps}")
    print(f"words     : {n_words}  ({n_words / seconds * 60:.1f} wpm, {n_words / seconds:.2f} w/s)")
    print(f"boundaries: {len(packed)}  -> {json_path}")
    first = packed[0]["f0"] if packed else -1
    last = packed[-1]["f1"] if packed else -1
    print(f"speech in : frame {first}..{last}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
